export type Lang = 'ko' | 'en'
export type Key = keyof typeof KO

export const t = (lang: Lang, key: Key) => (lang === 'en' ? EN : KO)[key]

export const pickLang = (stored: unknown, envLang: string | undefined): Lang => {
  if (stored === 'ko' || stored === 'en') return stored
  return (envLang ?? '').toLowerCase().startsWith('ko') ? 'ko' : 'en'
}
